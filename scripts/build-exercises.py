"""Build src/data/exercises.ts from free-exercise-db (Unlicense / public domain).

Usage: python3 scripts/build-exercises.py
Downloads the dataset, keeps equipment == "kettlebells", tidies the names,
assigns a movement pattern and adds a few staples written for Kettlebelt.
"""
import json
import os
import re
import urllib.request

SRC = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json'
IMG = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/'
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'data', 'exercises.ts')

RULES = [
    ('getup', r'Get-Up'),
    ('squat', r'Squat|Lunge|Thruster|Pistol'),
    ('hinge', r'Snatch|Swing|Clean|Deadlift|High Pull|Pass Between|Figure 8'),
    ('push', r'Press|Jerk|Pushup|Triceps'),
    ('pull', r'Row'),
    ('core', r'Windmill|Halo|Pirate|Seesaw'),
]


def pattern(name):
    for key, rx in RULES:
        if re.search(rx, name, re.I):
            return key
    return 'core'


def tidy(name):
    n = re.sub(r'\s+', ' ', name.replace('Kettlebells', '').replace('Kettlebell', '')).strip()
    n = n.replace('Front Squats With Two', 'Front squat, two bells')
    n = n.replace('Swings', 'Swing').replace('Squats', 'Squat').replace('Pushups', 'Push-ups')
    n = n.replace('Two-Arm', 'Two-hand').replace('One-Arm', 'One-arm')
    n = n[0].upper() + n[1:].lower()
    return n.replace('turkish', 'Turkish')


