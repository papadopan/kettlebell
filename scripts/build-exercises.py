HEADER = '''/**
 * Kettlebell exercise library. GENERATED by scripts/build-exercises.py; edit the script, not this file.
 *
 * Source: free-exercise-db by yuhonas (https://github.com/yuhonas/free-exercise-db),
 * released under the Unlicense (public domain). Exercises with equipment "kettlebells",
 * names tidied, plus a few staples written for Kettlebelt (ids starting with "kb-").
 * Photos load from the GitHub repo for now; bundle or self-host them before release.
 */

export type Pattern = 'hinge' | 'squat' | 'push' | 'pull' | 'getup' | 'carry' | 'core';
export type ExerciseLevel = 'beginner' | 'intermediate' | 'advanced';

export type Exercise = {
  id: string;
  name: string;
  /** Original name in free-exercise-db (empty for our own entries). */
  sourceName: string;
  pattern: Pattern;
  level: ExerciseLevel;
  mechanic: string;
  primary: string[];
  secondary: string[];
  instructions: string[];
  /** Start and finish photos (0–2). */
  images: string[];
};

export const PATTERNS: { id: Pattern; label: string }[] = [
  { id: 'hinge', label: 'Swings & hinges' },
  { id: 'squat', label: 'Squats & lunges' },
  { id: 'push', label: 'Presses' },
  { id: 'pull', label: 'Rows' },
  { id: 'getup', label: 'Get-ups' },
  { id: 'carry', label: 'Carries' },
  { id: 'core', label: 'Core & mobility' },
];

'''


def main():
    data = json.load(urllib.request.urlopen(SRC))
    out = []
    for x in data:
        if x.get('equipment') != 'kettlebells':
            continue
        out.append({
            'id': x['id'], 'name': tidy(x['name']), 'sourceName': x['name'], 'pattern': pattern(x['name']),
            'level': {'expert': 'advanced'}.get(x['level'], x['level']),
            'mechanic': x.get('mechanic') or 'compound',
            'primary': x['primaryMuscles'], 'secondary': x['secondaryMuscles'],
            'instructions': x['instructions'], 'images': [IMG + i for i in x['images']],
        })
    for e in EXTRA:
        out.append({'sourceName': '', 'mechanic': 'compound', 'images': [], **e})
    out.sort(key=lambda e: e['name'].lower())
    body = 'export const exercises: Exercise[] = ' + json.dumps(out, indent=2, ensure_ascii=False) + ';\n\n'
    body += 'export const findExercise = (id: string) => exercises.find((e) => e.id === id);\n'
    with open(OUT, 'w') as f:
        f.write(HEADER + body)
    print(f'wrote {len(out)} exercises to {os.path.normpath(OUT)}')


if __name__ == '__main__':
    main()
